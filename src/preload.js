'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  syncChange: (contents) => ipcRenderer.invoke('doc:syncChange', { contents }),
  listTabs: () => ipcRenderer.invoke('tabs:list'),
  activateTab: (id) => ipcRenderer.invoke('doc:activate', { id }),
  closeTab: (id) => ipcRenderer.invoke('doc:close', { id }),
  reorderTabs: (ids) => ipcRenderer.invoke('tabs:reorder', { ids }),
  reopenTab: () => ipcRenderer.invoke('tabs:reopen'),
  chooseFolder: () => ipcRenderer.invoke('tree:choose'),
  setTreeRoot: (root) => ipcRenderer.invoke('tree:setRoot', { root }),
  listDir: (dir) => ipcRenderer.invoke('tree:children', { dir }),
  openPath: (file) => ipcRenderer.invoke('tree:open', { file }),
  pathForFile: (file) => {
    try {
      return webUtils.getPathForFile(file);
    } catch {
      return '';
    }
  },
  onTreeChanged: (cb) => ipcRenderer.on('tree:changed', (_e, payload) => cb(payload)),
  save: () => ipcRenderer.invoke('doc:save'),
  saveAs: () => ipcRenderer.invoke('doc:saveAs'),
  open: () => ipcRenderer.invoke('doc:open'),
  newDoc: () => ipcRenderer.invoke('doc:new'),
  reloadFile: () => ipcRenderer.invoke('doc:reload'),
  normalizeDoc: (contents) => ipcRenderer.invoke('doc:normalize', { contents }),
  exportHtml: () => ipcRenderer.invoke('doc:exportHtml'),
  exportPdf: () => ipcRenderer.invoke('doc:exportPdf'),
  exportDocx: () => ipcRenderer.invoke('doc:exportDocx'),
  exportEpub: () => ipcRenderer.invoke('doc:exportEpub'),
  listBackups: () => ipcRenderer.invoke('backup:list'),
  info: () => ipcRenderer.invoke('app:info'),
  saveImage: (payload) => ipcRenderer.invoke('image:save', payload),
  discardDraft: () => ipcRenderer.invoke('draft:discard'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  onLoadDraft: (cb) => ipcRenderer.on('doc:loadDraft', (_e, payload) => cb(payload)),
  onLoaded: (cb) => ipcRenderer.on('doc:loaded', (_e, payload) => cb(payload)),
  onPreview: (cb) => ipcRenderer.on('preview:html', (_e, html) => cb(html)),
  onOutline: (cb) => ipcRenderer.on('outline:update', (_e, items) => cb(items)),
  onTabs: (cb) => ipcRenderer.on('tabs:update', (_e, list) => cb(list)),
  onSaveState: (cb) => ipcRenderer.on('save:state', (_e, payload) => cb(payload)),
  onTreeRoot: (cb) => ipcRenderer.on('tree:root', (_e, info) => cb(info)),
  reportError: (payload) => ipcRenderer.invoke('log:error', payload),
  logPath: () => ipcRenderer.invoke('log:path'),
  aiConfig: () => ipcRenderer.invoke('ai:config'),
  aiConfigure: (patch) => ipcRenderer.invoke('ai:configure', patch),
  aiComplete: (payload) => ipcRenderer.invoke('ai:complete', payload),
  aiStream: (payload) => ipcRenderer.invoke('ai:stream', payload),
  aiCancel: (requestId) => ipcRenderer.invoke('ai:cancel', { requestId }),
  aiHistoryGet: () => ipcRenderer.invoke('ai:history:get'),
  aiHistorySet: (turns) => ipcRenderer.invoke('ai:history:set', { turns }),
  aiTest: (patch) => ipcRenderer.invoke('ai:test', patch),
  openExternal: (url) => ipcRenderer.invoke('app:openExternal', { url }),
  lastExternal: () => ipcRenderer.invoke('app:lastExternal'),
  aiModels: (patch) => ipcRenderer.invoke('ai:models', patch),
  aiUsageList: () => ipcRenderer.invoke('ai:usage:list'),
  aiUsageExport: () => ipcRenderer.invoke('ai:usage:export'),
  aiUsageExportTo: (filePath) => ipcRenderer.invoke('ai:usage:exportPath', { filePath }),
  updateCheck: (feedUrl) => ipcRenderer.invoke('update:check', { feedUrl }),
  recentList: () => ipcRenderer.invoke('recent:list'),
  clipboardWrite: (text) => ipcRenderer.invoke('clipboard:write', { text }),
  clipboardRead: () => ipcRenderer.invoke('clipboard:read'),
  openDraftsFolder: () => ipcRenderer.invoke('drafts:open'),
  listDrafts: () => ipcRenderer.invoke('drafts:list'),
  restoreDraft: (file) => ipcRenderer.invoke('drafts:restore', { file }),
  purgeDrafts: (olderThanDays) => ipcRenderer.invoke('drafts:purge', { olderThanDays }),
  deleteDraft: (file) => ipcRenderer.invoke('drafts:delete', { file }),
  onCrashed: (cb) => ipcRenderer.on('app:crashed', (_e, payload) => cb(payload)),
  onFirstRun: (cb) => ipcRenderer.on('app:first-run', (_e, payload) => cb(payload)),
  onPreflight: (cb) => ipcRenderer.on('app:preflight', (_e, payload) => cb(payload)),
  onSessionTruncated: (cb) => ipcRenderer.on('session:truncated', (_e, payload) => cb(payload)),
  onSessionRestored: (cb) => ipcRenderer.on('session:restored', (_e, payload) => cb(payload)),
  exportPreview: () => ipcRenderer.invoke('export:preview'),
  exportNamePreview: (template) => ipcRenderer.invoke('export:namePreview', { template }),
  backupInfo: () => ipcRenderer.invoke('doc:backupInfo'),
  backupsList: () => ipcRenderer.invoke('doc:backups'),
  restoreBackup: (filePath) => ipcRenderer.invoke('doc:restoreBackup', { filePath }),
  restoreDecision: (args) => ipcRenderer.invoke('app:restoreDecision', args),
  settingsExport: () => ipcRenderer.invoke('settings:export'),
  settingsImport: () => ipcRenderer.invoke('settings:import'),
  settingsExportTo: (filePath) => ipcRenderer.invoke('settings:exportPath', { filePath }),
  settingsImportFrom: (filePath) => ipcRenderer.invoke('settings:importPath', { filePath }),
  onAiChunk: (cb) => ipcRenderer.on('ai:chunk', (_e, payload) => cb(payload)),
  onAiRetry: (cb) => ipcRenderer.on('ai:retry', (_e, payload) => cb(payload)),
  onFileExternal: (cb) => ipcRenderer.on('file:external', (_e, payload) => cb(payload)),
  onStatus: (cb) => ipcRenderer.on('app:status', (_e, payload) => cb(payload)),
  onMenuAction: (cb) => ipcRenderer.on('menu:action', (_e, action) => cb(action)),
});
