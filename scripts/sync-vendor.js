'use strict';

// Copies third-party runtime assets the renderer loads by relative URL.
// Run through `npm run sync-assets` (also wired to postinstall).

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const vendor = path.join(root, 'src', 'renderer', 'vendor');

function copyFile(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function copyDir(from, to, filter = () => true) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dst, filter);
    else if (filter(entry.name)) copyFile(src, dst);
  }
}

const katexDist = path.join(root, 'node_modules', 'katex', 'dist');
const hljsStyles = path.join(root, 'node_modules', 'highlight.js', 'styles');
const katexCss = path.join(vendor, 'katex', 'katex.min.css');

if (!fs.existsSync(katexDist)) {
  console.error('sync-assets: katex is not installed yet; run npm install first');
  process.exit(0);
}

copyFile(path.join(katexDist, 'katex.min.css'), katexCss);
copyDir(path.join(katexDist, 'fonts'), path.join(vendor, 'katex', 'fonts'), (n) => n.endsWith('.woff2'));
const mermaidDist = path.join(root, 'node_modules', 'mermaid', 'dist', 'mermaid.min.js');
if (fs.existsSync(mermaidDist)) {
  copyFile(mermaidDist, path.join(vendor, 'mermaid', 'mermaid.min.js'));
} else {
  console.error('sync-assets: mermaid is not installed; diagrams will not render');
}

copyFile(path.join(hljsStyles, 'github.css'), path.join(vendor, 'hljs', 'github.css'));
copyFile(path.join(hljsStyles, 'github-dark.css'), path.join(vendor, 'hljs', 'github-dark.css'));
fs.writeFileSync(
  path.join(vendor, 'README.md'),
  'Generated by scripts/sync-vendor.js from node_modules. Do not edit by hand.\n',
  'utf8'
);

const bytes = (p) => {
  let total = 0;
  for (const entry of fs.readdirSync(p, { recursive: true, withFileTypes: true })) {
    if (entry.isFile()) total += fs.statSync(path.join(entry.parentPath ?? entry.path, entry.name)).size;
  }
  return Math.round(total / 1024) + ' KB';
};
const mermaidSize = fs.existsSync(path.join(vendor, 'mermaid')) ? bytes(path.join(vendor, 'mermaid')) : 'missing';
console.log(
  `sync-assets: katex css+fonts (${bytes(path.join(vendor, 'katex'))}), hljs theme ok, mermaid ${mermaidSize}`
);
